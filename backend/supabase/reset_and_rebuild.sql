-- ============================================================================
-- STEP 2: CREATE TABLES
-- ============================================================================

-- 1. Clubs (5 clubs: tech, sports, culture, multimedia, management)
CREATE TABLE clubs (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(80)  NOT NULL UNIQUE,
    slug           varchar(40)  NOT NULL UNIQUE,
    code_prefix    varchar(10)  NOT NULL UNIQUE,
    description    text         NOT NULL DEFAULT '',
    head_name      varchar(120) NOT NULL DEFAULT '',
    contact_email  varchar(255),
    contact_phone  varchar(20),
    image_path     varchar(255)
);

-- 2. Student Registration Details
CREATE TABLE students (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usn             varchar(20)  NOT NULL UNIQUE,
    full_name       varchar(120) NOT NULL,
    email           varchar(255) NOT NULL UNIQUE,
    phone           varchar(15)  NOT NULL,
    branch          varchar(40)  NOT NULL,
    joining_year    integer      NOT NULL,
    email_verified  boolean      NOT NULL DEFAULT false,
    created_at      timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_students_usn   ON students (usn);
CREATE INDEX ix_students_email ON students (email);

-- 3. Admin Login Details & Club Coordinator Details
CREATE TABLE admins (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       varchar(60)  NOT NULL UNIQUE,
    password_hash  varchar(255) NOT NULL,
    role           varchar(20)  NOT NULL DEFAULT 'admin' CHECK (role IN ('admin', 'superadmin', 'coordinator')),
    active         boolean      NOT NULL DEFAULT true,
    club_id        integer REFERENCES clubs(id) ON DELETE SET NULL,
    created_at     timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_admins_username ON admins (username);
CREATE INDEX ix_admins_club_id  ON admins (club_id);

-- 4. Club Memberships (links students to clubs with unique Club ID)
CREATE TABLE memberships (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id       integer     NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    club_id          integer     NOT NULL REFERENCES clubs(id) ON DELETE CASCADE,
    membership_code  varchar(40) NOT NULL UNIQUE,
    status           varchar(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'pending', 'suspended')),
    joined_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_membership_student_club UNIQUE (student_id, club_id)
);
CREATE INDEX ix_memberships_student_id ON memberships (student_id);
CREATE INDEX ix_memberships_club_id    ON memberships (club_id);
CREATE INDEX ix_memberships_code       ON memberships (membership_code);

-- 5. Club Counters (gap-free sequential membership IDs per club & year)
CREATE TABLE club_counters (
    club_id      integer NOT NULL REFERENCES clubs(id) ON DELETE CASCADE,
    year         integer NOT NULL,
    last_number  integer NOT NULL DEFAULT 0,
    PRIMARY KEY (club_id, year)
);

-- 6. Announcements (club_id NULL = global / all clubs)
CREATE TABLE announcements (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         varchar(200) NOT NULL,
    message       text         NOT NULL,
    club_id       integer REFERENCES clubs(id) ON DELETE SET NULL,
    published     boolean      NOT NULL DEFAULT false,
    published_at  timestamptz,
    created_by    integer      NOT NULL REFERENCES admins(id),
    created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_announcements_club_id ON announcements (club_id);

-- 7. Photos metadata (linked to Supabase Storage bucket 'club-photos')
CREATE TABLE photos (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id      integer      NOT NULL REFERENCES clubs(id) ON DELETE CASCADE,
    title        varchar(150) NOT NULL,
    event_name   varchar(150) NOT NULL DEFAULT '',
    image_path   varchar(255) NOT NULL,
    uploaded_by  integer      NOT NULL REFERENCES admins(id),
    uploaded_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_photos_club_id ON photos (club_id);

-- 8. Email OTPs
CREATE TABLE email_otps (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        varchar(255) NOT NULL,
    purpose      varchar(20)  NOT NULL CHECK (purpose IN ('register', 'login')),
    otp_hash     varchar(64)  NOT NULL,
    expires_at   timestamptz  NOT NULL,
    attempts     integer      NOT NULL DEFAULT 0,
    consumed_at  timestamptz,
    created_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_email_otps_lookup ON email_otps (email, purpose);

-- 9. Pending Registrations (parked until OTP verification succeeds)
CREATE TABLE pending_registrations (
    id            varchar(32)  PRIMARY KEY,
    usn           varchar(20)  NOT NULL,
    full_name     varchar(120) NOT NULL,
    email         varchar(255) NOT NULL,
    phone         varchar(15)  NOT NULL,
    branch        varchar(40)  NOT NULL,
    joining_year  integer      NOT NULL,
    club_id       integer      NOT NULL REFERENCES clubs(id) ON DELETE CASCADE,
    link_id       integer,
    expires_at    timestamptz  NOT NULL
);
CREATE INDEX ix_pending_registrations_email ON pending_registrations (email);

-- 10. Registration Links
CREATE TABLE registration_links (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id       integer      NOT NULL REFERENCES clubs(id) ON DELETE CASCADE,
    public_token  varchar(40)  NOT NULL UNIQUE,
    title         varchar(150) NOT NULL,
    active        boolean      NOT NULL DEFAULT true,
    starts_at     timestamptz,
    ends_at       timestamptz,
    created_by    integer      NOT NULL REFERENCES admins(id),
    created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_registration_links_club_id ON registration_links (club_id);

-- 11. Audit Logs
CREATE TABLE audit_logs (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id    integer REFERENCES admins(id) ON DELETE SET NULL,
    action      varchar(60)  NOT NULL,
    target      varchar(120) NOT NULL DEFAULT '',
    detail      text         NOT NULL DEFAULT '',
    ip          varchar(64)  NOT NULL DEFAULT '',
    created_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_logs_action ON audit_logs (action);

-- ============================================================================
-- STEP 3: HELPFUL VIEWS FOR SUPABASE TABLE EDITOR
-- ============================================================================

-- View member details organized by club
CREATE VIEW club_member_details AS
SELECT
    m.id            AS membership_id,
    c.name          AS club_name,
    c.slug          AS club_slug,
    m.membership_code,
    m.status,
    s.usn,
    s.full_name,
    s.email,
    s.phone,
    s.branch,
    s.joining_year,
    s.email_verified,
    m.joined_at
FROM memberships m
JOIN students s ON s.id = m.student_id
JOIN clubs    c ON c.id = m.club_id
ORDER BY c.id ASC, m.joined_at DESC;

-- View admin & coordinator login details with assigned club
CREATE VIEW coordinator_details AS
SELECT
    a.id,
    a.username,
    a.role,
    a.active,
    COALESCE(c.name, 'All Clubs (Superadmin)') AS assigned_club,
    c.slug                                     AS club_slug,
    a.created_at
FROM admins a
LEFT JOIN clubs c ON c.id = a.club_id
ORDER BY a.id ASC;


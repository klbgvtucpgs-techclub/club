-- ---------- clubs ----------
CREATE TABLE IF NOT EXISTS clubs (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(80)  NOT NULL UNIQUE,
    slug           varchar(40)  NOT NULL UNIQUE,
    code_prefix    varchar(10)  NOT NULL UNIQUE,
    description    text         NOT NULL DEFAULT '',
    head_name      varchar(120) NOT NULL DEFAULT '',
    contact_email  varchar(255),
    contact_phone  varchar(20),
    image_path     varchar(255)
);

-- ---------- students ----------
CREATE TABLE IF NOT EXISTS students (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usn             varchar(20)  NOT NULL UNIQUE,
    full_name       varchar(120) NOT NULL,
    email           varchar(255) NOT NULL UNIQUE,
    phone           varchar(15)  NOT NULL,
    branch          varchar(40)  NOT NULL,
    joining_year    integer      NOT NULL,
    email_verified  boolean      NOT NULL DEFAULT false,
    created_at      timestamptz  NOT NULL DEFAULT now()
);

-- ---------- admins ----------
CREATE TABLE IF NOT EXISTS admins (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       varchar(60)  NOT NULL UNIQUE,
    password_hash  varchar(255) NOT NULL,
    role           varchar(20)  NOT NULL DEFAULT 'admin' CHECK (role IN ('admin', 'superadmin')),
    active         boolean      NOT NULL DEFAULT true,
    created_at     timestamptz  NOT NULL DEFAULT now()
);

-- ---------- memberships ----------
CREATE TABLE IF NOT EXISTS memberships (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id       integer     NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    club_id          integer     NOT NULL REFERENCES clubs(id),
    membership_code  varchar(40) NOT NULL UNIQUE,
    status           varchar(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'pending', 'suspended')),
    joined_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_membership_student_club UNIQUE (student_id, club_id)
);
CREATE INDEX IF NOT EXISTS ix_memberships_student_id ON memberships (student_id);
CREATE INDEX IF NOT EXISTS ix_memberships_club_id    ON memberships (club_id);

-- ---------- club_counters (gap-free membership numbers per club and joining year) ----------
CREATE TABLE IF NOT EXISTS club_counters (
    club_id      integer NOT NULL REFERENCES clubs(id),
    year         integer NOT NULL,
    last_number  integer NOT NULL DEFAULT 0,
    PRIMARY KEY (club_id, year)
);

-- ---------- announcements (club_id NULL = global) ----------
CREATE TABLE IF NOT EXISTS announcements (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         varchar(200) NOT NULL,
    message       text         NOT NULL,
    club_id       integer REFERENCES clubs(id),
    published     boolean      NOT NULL DEFAULT false,
    published_at  timestamptz,
    created_by    integer      NOT NULL REFERENCES admins(id),
    created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_announcements_club_id ON announcements (club_id);

-- ---------- photos ----------
CREATE TABLE IF NOT EXISTS photos (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id      integer      NOT NULL REFERENCES clubs(id),
    title        varchar(150) NOT NULL,
    event_name   varchar(150) NOT NULL DEFAULT '',
    image_path   varchar(255) NOT NULL,
    uploaded_by  integer      NOT NULL REFERENCES admins(id),
    uploaded_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_photos_club_id ON photos (club_id);

-- ---------- email_otps ----------
CREATE TABLE IF NOT EXISTS email_otps (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        varchar(255) NOT NULL,
    purpose      varchar(20)  NOT NULL CHECK (purpose IN ('register', 'login')),
    otp_hash     varchar(64)  NOT NULL,
    expires_at   timestamptz  NOT NULL,
    attempts     integer      NOT NULL DEFAULT 0,
    consumed_at  timestamptz,
    created_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_email_otps_lookup ON email_otps (email, purpose);

-- ---------- pending_registrations (form data parked until the OTP is verified) ----------
CREATE TABLE IF NOT EXISTS pending_registrations (
    id            varchar(32)  PRIMARY KEY,
    usn           varchar(20)  NOT NULL,
    full_name     varchar(120) NOT NULL,
    email         varchar(255) NOT NULL,
    phone         varchar(15)  NOT NULL,
    branch        varchar(40)  NOT NULL,
    joining_year  integer      NOT NULL,
    club_id       integer      NOT NULL REFERENCES clubs(id),
    link_id       integer,
    expires_at    timestamptz  NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_pending_registrations_email ON pending_registrations (email);

-- ---------- registration_links ----------
CREATE TABLE IF NOT EXISTS registration_links (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id       integer      NOT NULL REFERENCES clubs(id),
    public_token  varchar(40)  NOT NULL UNIQUE,
    title         varchar(150) NOT NULL,
    active        boolean      NOT NULL DEFAULT true,
    starts_at     timestamptz,
    ends_at       timestamptz,
    created_by    integer      NOT NULL REFERENCES admins(id),
    created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_registration_links_club_id ON registration_links (club_id);

-- ---------- audit_logs ----------
CREATE TABLE IF NOT EXISTS audit_logs (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id    integer REFERENCES admins(id),
    action      varchar(60) NOT NULL,
    target      varchar(120) NOT NULL DEFAULT '',
    detail      text         NOT NULL DEFAULT '',
    ip          varchar(64)  NOT NULL DEFAULT '',
    created_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_audit_logs_action ON audit_logs (action);

